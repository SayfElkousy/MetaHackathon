"""Research report (Markdown + standalone HTML) for one pipeline run."""
from __future__ import annotations

import html
import json
from pathlib import Path


def _fmt(v, nd=2):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def build_markdown(res: dict) -> str:
    L = []
    L.append(f"# Research report: {res['case_id']}")
    if res.get("synthetic"):
        L.append("\n> **SYNTHETIC DEMONSTRATION.** Phantom data generated by the software. No value in this report is a patient measurement or a measured performance.\n")
    L.append("> Investigational research output. It does not establish that any scaffold heals an ACL, restores function, or reduces reinjury. "
             "Anatomy shown is *estimated* from imaging; internal pathways are *hypothesized*.\n")
    L.append("## Inputs")
    for role in ("injured", "contralateral"):
        s = res.get(f"{role}_image", {})
        L.append(f"- **{role}**: shape {s.get('shape')}, spacing {s.get('spacing_mm')} mm, {s.get('axcodes')}, "
                 f"physical metadata verified: {s.get('physical_verified')} ({s.get('physical_source')})")
    reg = res.get("registration")
    if reg:
        L.append("\n## Bilateral registration (estimated)")
        L.append(f"Method: {reg['method']}")
        L.append("| bone | ICP rms (mm) | inliers <2 mm | surface rms (mm) | surface HD95 (mm) |\n|---|---|---|---|---|")
        for b in ("femur", "tibia"):
            i = reg[f"{b}_icp"]
            s = reg["qc"]["surface"][b]
            L.append(f"| {b} | {_fmt(i['rms_mm'])} | {_fmt(i['inlier_fraction_2mm'])} | {_fmt(s['rms_mm'])} | {_fmt(s['hd95_mm'])} |")
        L.append(f"\nRelative tibiofemoral rotation between scans: {_fmt(reg['relative_tibiofemoral_rotation_deg'], 1)} deg")
        lm = reg["qc"].get("landmarks") or {}
        if lm.get("n"):
            L.append(f"\nIndependent landmark error (not used for registration; includes true asymmetry): mean {_fmt(lm['mean_mm'])} mm over {lm['n']} landmarks")
            for k, v in sorted(lm["per_landmark_mm"].items()):
                L.append(f"- {k}: {_fmt(v)} mm")
        else:
            L.append("\nNo independent landmarks: registration accuracy is **unverified**.")
    if res.get("estimates"):
        L.append("\n## Native ACL estimates (estimated anatomy, alternatives)")
        L.append("| estimate | length (mm) | volume (mm³) | mean CSA (mm²) | conflicts |\n|---|---|---|---|---|")
        for n, e in res["estimates"].items():
            L.append(f"| {n} | {_fmt(e['straight_length_mm'],1)} | {_fmt(e['volume_mm3'],0)} | {_fmt(e['mean_area_mm2'],1)} | {len(e['conflicts'])} |")
        for n, e in res["estimates"].items():
            for c in e["conflicts"]:
                L.append(f"- ⚠ {n}: {c}")
            for c in e["notes"]:
                L.append(f"- {n}: {c}")
    if res.get("uncertainty"):
        L.append("\n## Uncertainty (by source; not combined)")
        L.append("| source | femoral footprint SD (mm) | tibial footprint SD (mm) | uncertain voxels | n |\n|---|---|---|---|---|")
        for k, u in res["uncertainty"].items():
            if isinstance(u, dict):
                L.append(f"| {k} | {_fmt(u['femoral_fp_sd_mm'])} | {_fmt(u['tibial_fp_sd_mm'])} | {u['uncertain_voxels']} | {u['n']} |")
        L.append("\nNot represented: " + "; ".join(res["uncertainty"].get("not_represented", [])))
    ab = res.get("abstention")
    if ab:
        L.append("\n## Abstention checks (engineering thresholds, not validated)")
        L.append("| check | status | detail |\n|---|---|---|")
        for c in ab["checks"]:
            L.append(f"| {c['name']} | {c['status']} | {html.escape(c['detail'])} |")
        L.append(f"\nAbstain estimation: **{ab['abstain_estimation']}**; abstain design export: **{ab['abstain_design_export']}**")
    rv = res.get("review", {}).get("anatomy_estimate", {})
    L.append(f"\n## Expert review\nAnatomy estimate review status: **{rv.get('status')}** (reviewer: {rv.get('reviewer')})")
    sc = res.get("scaffold")
    if sc:
        L.append("\n## Investigational scaffold candidate (hypothesized)")
        L.append(f"Built from estimate: `{sc['estimate_used']}`; applicable: {sc['applicable']}")
        for n in sc["notes"]:
            L.append(f"- {n}")
        if sc.get("validation"):
            v = sc["validation"]
            m = v["mesh"]
            L.append(f"\nMesh: watertight={m['watertight']}, winding consistent={m['winding_consistent']}, components={m['connected_components']}, "
                     f"self-intersecting pairs={m['self_intersections'].get('intersecting_pairs')}, volume={_fmt(m['volume_mm3'],1)} mm³")
            L.append(f"Min solid feature: {_fmt(v['min_solid_feature_mm'])} mm; void fraction in envelope: {_fmt(v['porosity']['void_fraction_within_envelope'])}")
            if "bone" in v:
                L.append(f"Bone clearance (min): {_fmt(v['bone']['min_clearance_mm'])} mm; vertices inside bone: {v['bone']['vertices_inside_bone']}")
            if "remnant" in v:
                L.append(f"Remnant overlap: {_fmt(v['remnant']['overlap_mm3'])} mm³")
            L.append(f"Geometric checks passed: **{v['geometric_checks_passed']}** {v['failures'] or ''}")
            L.append(f"\n_{v['disclaimer']}_")
        g = sc.get("export_gate")
        if g:
            L.append(f"\nExport gate: allowed = **{g['allowed']}**" + ("" if g["allowed"] else " — " + "; ".join(g["reasons"])))
        mech = sc.get("mechanics")
        if mech:
            L.append("\n## Simplified mechanics (1D axial model, not FE)")
            if mech.get("status") == "blocked":
                L.append(f"Blocked: {mech['reason']}")
            else:
                L.append(f"{mech['label']}")
                L.append(f"- E_solid = {mech['inputs']['E_solid_MPa']} MPa (source: {mech['inputs']['E_source']})")
                L.append(f"- axial stiffness {_fmt(mech['axial_stiffness_N_per_mm'],1)} N/mm; min solid area {_fmt(mech['min_solid_area_mm2'],2)} mm²; "
                         f"max nominal stress {_fmt(mech['max_nominal_stress_MPa'])} MPa at {_fmt(mech['force_N'],1)} N")
                if "sensitivity" in mech:
                    lo, hi = mech["sensitivity"]["stiffness_range_N_per_mm"]
                    L.append(f"- sensitivity over {mech['sensitivity']['varied']}: stiffness {lo:.1f}–{hi:.1f} N/mm")
                for a in mech["assumptions"]:
                    L.append(f"  - assumption: {a}")
    L.append("\n## Separation of claims")
    L.append("| question | addressed here? |\n|---|---|")
    L.append("| geometric fit of candidate to estimated anatomy | yes (estimated anatomy) |")
    L.append("| mechanical behaviour | only under the stated 1D model, if run |")
    L.append("| biological healing | **no** |")
    L.append("| clinical reinjury outcome | **no** |")
    return "\n".join(L) + "\n"


def write_report(run_dir, res: dict) -> Path:
    run_dir = Path(run_dir)
    md = build_markdown(res)
    (run_dir / "report.md").write_text(md)
    body = []
    in_table = False
    for line in md.splitlines():
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(set(c) <= set("-") for c in cells):
                continue
            if not in_table:
                body.append("<table>")
                in_table = True
                body.append("<tr>" + "".join(f"<th>{c}</th>" for c in cells) + "</tr>")
            else:
                body.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            body.append("</table>")
            in_table = False
        if line.startswith("# "):
            body.append(f"<h1>{html.escape(line[2:])}</h1>")
        elif line.startswith("## "):
            body.append(f"<h2>{html.escape(line[3:])}</h2>")
        elif line.startswith("> "):
            body.append(f"<div class='banner'>{line[2:].replace('**', '')}</div>")
        elif line.startswith("- ") or line.startswith("  - "):
            body.append(f"<li>{html.escape(line.strip()[2:])}</li>")
        elif line.strip():
            body.append(f"<p>{line.replace('**', '')}</p>")
    if in_table:
        body.append("</table>")
    page = f"""<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Research report</title>
<style>body{{font:14px/1.5 system-ui,sans-serif;max-width:960px;margin:24px auto;padding:0 16px;color:#1d2330;background:#fff}}
table{{border-collapse:collapse;margin:8px 0;font-size:13px}}td,th{{border:1px solid #ccd;padding:3px 8px;text-align:left}}
.banner{{background:#fff4d6;border-left:4px solid #d9a400;padding:8px 12px;margin:8px 0}}h2{{border-bottom:1px solid #dde;padding-bottom:4px}}</style>
</head><body>{''.join(body)}</body></html>"""
    (run_dir / "report.html").write_text(page)
    return run_dir / "report.md"
