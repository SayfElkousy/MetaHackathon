"""Generate tools/web/ws/index.html from the designer page (tools/web/v2/index.html).

The workspace reuses the designer's DOM verbatim (same element ids, same script), placed into the tabbed layout:
header controls -> top bar, #stage -> the 'Scaffold' view, #side -> the scaffold inspector. Re-run after editing
the designer page:  python tools/build_workspace_html.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "web", "v2", "index.html")
DST = os.path.join(ROOT, "tools", "web", "ws", "index.html")


def grab(s, start_re, end_tag):
    m = re.search(start_re, s)
    i = m.start()
    depth, j = 0, i
    tag = end_tag.strip("</>")
    for t in re.finditer(r"<(/?)%s\b[^>]*>" % tag, s[i:]):
        depth += -1 if t.group(1) else 1
        if depth == 0:
            j = i + t.end()
            break
    return s[i:j]


def main():
    s = open(SRC, encoding="utf-8").read()
    head = re.search(r'<header id="top">(.*?)</header>', s, re.S).group(1)
    head = head.replace('<b class="brand">ACL repair designer</b>', '')
    stage = grab(s, r'<section id="stage">', "</section>")
    side = grab(s, r'<aside id="side">', "</aside>")
    dialogs = "\n".join(grab(s, r'<dialog id="%s">' % d, "</dialog>") for d in ("caseDlg", "conflictDlg"))
    guard = re.search(r"(<script>\s*// If the 3D library.*?</script>)", s, re.S).group(1)
    importmap = re.search(r'(<script type="importmap">.*?</script>)', s, re.S).group(1)
    out = f"""<!doctype html>
<!-- GENERATED by tools/build_workspace_html.py from tools/web/v2/index.html: edit those, then re-run. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>ACL Workspace</title>
<link rel="stylesheet" href="/v2/style.css">
<link rel="stylesheet" href="/ws/ws.css">
{importmap}
</head><body class="ws">
<header id="wsTop">
  <b class="brand">ACL Workspace</b>
  <span class="tbgroup" role="group" aria-label="Layout presets">
    <button id="btnPresetMpr" title="Axial, sagittal and coronal MRI planes next to the scaffold">MPR + Scaffold</button><button id="btnPresetScaf" title="Scaffold only">Scaffold</button><button id="btnPresetReview" title="Sagittal + coronal with quality control and evidence">Review</button>
    <button id="btnAddView" title="Open a view in the active pane">+ View</button>
  </span>
  <span class="designer-head">{head}</span>
  <button id="btnMuse" class="musebtn" title="Muse assistant (Ctrl/⌘+K)">Muse</button>
</header>
<main id="wsMain">
  <aside id="left"><div id="browser"></div></aside>
  <section id="panes"></section>
  <aside id="inspector">
    <div id="insSwitch" role="tablist"><button data-ins="imaging">Imaging</button><button data-ins="scaffold" class="on">Scaffold</button></div>
    <div id="insImg" hidden></div>
    <div id="insScaf"></div>
  </aside>
</main>
<div id="muse" class="min"></div>
<div id="menu" class="menu" hidden></div>
<div id="toast" class="toast" hidden></div>
<div id="parking" hidden>
{stage}
{side}
</div>
{dialogs}
{guard}
<script type="module" src="/v2/app.js"></script>
<script type="module" src="/ws/ws.js"></script>
</body></html>
"""
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    open(DST, "w", encoding="utf-8").write(out)
    print(DST)


if __name__ == "__main__":
    main()
